"""Unroll the loops nvcc unrolled on its own: no lowering site flagged them, and cicc copied their bodies anyway.

``117_unroll_loops`` spends the flags. Every other loop reached nvcc as a loop, and cicc (CUDA 13.0, LLVM-based)
unrolled it by a size rule of its own; ptxas does not, so this pass states that rule in Kernel IR, and both code
generators read loops already unrolled the way cicc did. The rule was read off cicc's PTX for ``sm_120`` across trip
counts and body sizes. A body's size is the work one trip does (:func:`_size`): one for each memory access, fold and
branch, and one for each operation whose value changes from trip to trip, a math function counting the instructions
cicc writes for it (``_COST``, in the form ``130_approximate_math`` will pick under the live precision decisions). What
does not change across trips cicc computed once ahead of the loop, so it counts nothing.

- **A serial ``Loop`` over a static extent** of ``N`` trips is written out in full when ``N·(size + 2) ≤ 480``. Else
  it steps ``C`` trips at a time, ``C`` the largest power of two that divides ``N`` with ``C·(size + 2) ≤ 199``. It
  stays as it is when ``N`` is odd: cicc then copies the body four times with the exit test between the third copy
  and the fourth, which this does not write. Where the rule gives two copies, ptxas copied cicc's loop four times
  again (the f32 register-tile matmuls' 128-trip ``_ki`` loop: 128 FFMA from cicc's PTX on ``sm_90``), so such a
  loop steps eight trips where eight divide ``N``.
- **A loop whose trips only the launch knows** (a symbolic extent, :func:`_unroll.runtime_bound`) takes ``C`` copies,
  the largest of 16, 8, 4 and 2 with ``C·(size + 7) ≤ 228``, none past a size of 89, in cicc's shape: a loop stepping
  ``C`` trips while that many are left, then the trips left in blocks of half as many copies down to one, four and a
  loop of one copy past 8 copies (:func:`_unroll._runtime`).
- **A strided loop whose start differs between threads**, over a static extent that leaves every thread the same
  ``N`` trips, steps ``C`` trips at a time from 24 trips on: ``C`` the largest power of two dividing ``N``, at most
  16, and none past a body size of 89. cicc copied such a loop 16 times where it could bound the start (a lane);
  where it could not, it gave it four copies that ptxas copied four times again. Below 24 trips, and where the
  threads' trips differ, cicc left the loop to ptxas, and so does this pass.

Every loop the pass leaves stepping several trips at a time says it is ``unrolled``. The PTX compiler keeps such a
loop as it is (``.pragma "nounroll"``): cicc marks the two loops of a runtime unroll so, and leaves its static partial
unroll unmarked, but ptxas then left those loops alone where it unrolls the more compact loops of the PTX compiler in
full. The CUDA renderer writes what cicc wrote: ``#pragma unroll 1`` on the runtime-bound ones only.

Only a body of target-neutral statements is sized. A loop holding a barrier, an asynchronous copy, a shuffle or a
fragment statement stays as it is: cicc does not unroll a loop with a barrier at run time, and left the tensor-core
loops over a symbolic K rolled. A loop already ``unrolled`` is taken no further, so the pass is idempotent.

The numbers are nvcc's, kept as a fixed rule so code generated by either path keeps the shape nvcc gave it, like the
two limits of ``117``; how many copies a loop takes is a decision that moves under the ``UNROLL`` knob. It runs after
``117``, so a written-out inner loop counts in its outer loop's size as it did for cicc, and before
``119_vectorize_copies``, which widens the runs of loads the copies line up.
"""

from __future__ import annotations

from dataclasses import replace

from emmy.compiler.context import Context
from emmy.compiler.graph import Node
from emmy.compiler.ir.expression import (
    BinaryExpression,
    CastExpression,
    Expression,
    FunctionCallExpression,
    Literal,
    TernaryExpression,
    Var,
)
from emmy.compiler.ir.kernel import KernelOp
from emmy.compiler.ir.stmt import Accum, Assign, Cond, Init, Let, Load, Loop, Select, Statement, StridedLoop, Write
from emmy.compiler.pipeline import Pattern, RuleSkipped
from emmy.compiler.pipeline.passes.lowering.kernel._approximate import approximate_forms
from emmy.compiler.pipeline.passes.lowering.kernel._unroll import unroll_where

PATTERN = [Pattern("root", KernelOp)]

#: The statements a sized body holds: the target-neutral ones.
_NEUTRAL = (Load, Assign, Select, Accum, Write, Init, Let, Cond, Loop, StridedLoop)

#: The instructions cicc writes for one call (``nvcc -ptx`` of CUDA 13.0, ``sm_120``); any other operation is one.
_COST = {
    "exp": 14,
    "exp_fast": 2,
    "expm1": 27,
    "log": 28,
    "log_fast": 2,
    "log2": 30,
    "log10": 29,
    "log1p": 32,
    "sin": 88,
    "cos": 89,
    "tan": 87,
    "tanh": 17,
    "sinh": 30,
    "cosh": 21,
    "arctan": 20,
    "arcsin": 24,
    "arccos": 27,
    "erf": 26,
    "pow": 113,
    "power": 113,
    "pow_fast": 3,
    "sigmoid": 15,
    "sigmoid_fast": 4,
}

#: A static loop: the overhead of a trip, the size of a loop written out in full, of a loop stepping several trips.
_STATIC_TRIP, _WHOLE, _PARTIAL = 2, 480, 199
#: A runtime-bound loop: the overhead of a trip, the size of the stepping loop, its most copies, the largest body.
_RUNTIME_TRIP, _RUNTIME, _RUNTIME_COPIES, _RUNTIME_LARGEST = 7, 228, 16, 89
#: The copies ptxas made of each trip of a static loop cicc copied twice.
_PTXAS_AGAIN = 4
#: A strided loop from a start that differs between threads: the fewest trips it is copied from.
_THREAD_START_LEAST = 24


def rewrite(root: Node, ctx: Context) -> KernelOp:
    op: KernelOp = root.op
    forms = approximate_forms(ctx)
    body = unroll_where(op.body, lambda loop, trips: _copies(loop, trips, forms))
    if body == op.body:
        raise RuleSkipped("no loop nvcc would have unrolled")
    return replace(op, body=body, knobs=dict(op.knobs))


def _copies(loop: Statement, trips: tuple[int, int] | None, forms: dict[str, str]) -> int | None:
    """The copies cicc gave ``loop`` (the module doc), or ``None``."""
    if loop.unrolled or not all(isinstance(stmt, _NEUTRAL) for stmt in loop.body.iter()):
        return None
    size = _size(loop, forms)
    if trips is None:
        fits = (n for n in _powers(_RUNTIME_COPIES) if n * (size + _RUNTIME_TRIP) <= _RUNTIME)
        return next(fits, None) if size <= _RUNTIME_LARGEST else None
    if isinstance(loop, StridedLoop):
        copies = min(_RUNTIME_COPIES, trips[1] & -trips[1])
        uniform = trips[0] == trips[1] >= _THREAD_START_LEAST and not isinstance(loop.start, Literal)
        return copies if uniform and copies > 1 and size <= _RUNTIME_LARGEST else None
    if trips[1] < 1:
        return None
    if trips[1] * (size + _STATIC_TRIP) <= _WHOLE:
        return trips[1]
    copies = next((n for n in _powers(trips[1] & -trips[1]) if n * (size + _STATIC_TRIP) <= _PARTIAL), None)
    return _PTXAS_AGAIN * copies if copies == 2 and trips[1] % (_PTXAS_AGAIN * copies) == 0 else copies


def _powers(most: int) -> list[int]:
    """The powers of two from ``most`` down to 2."""
    return [most >> k for k in range(most.bit_length() - 1)]


def _size(loop: Statement, forms: dict[str, str]) -> int:
    """The work one trip of ``loop`` does: one per memory access, fold, selection, branch and inner loop, and one for
    each operation whose value changes from trip to trip (it reads the axis or a name the body defines). An access
    whose address changes pays one more for it, and the operations of its index that are no sum of scaled terms."""
    changing = {loop.axis.name} | {name for stmt in loop.body.iter() for name in stmt.defines()}
    changing |= {stmt.axis.name for stmt in loop.body.iter() if isinstance(stmt, (Loop, StridedLoop))}

    def varies(expression: Expression) -> bool:
        return bool(expression.free_vars() & changing)

    def work(expression: Expression) -> int:
        return sum(_cost(term, forms) for term in expression.subterms() if varies(term))

    def beyond_affine(coord: Expression) -> int:
        if not varies(coord) or isinstance(coord, Var):
            return 0
        if isinstance(coord, BinaryExpression) and coord.op in ("+", "-"):
            return beyond_affine(coord.left) + beyond_affine(coord.right)
        if isinstance(coord, BinaryExpression) and coord.op == "*" and not (varies(coord.left) and varies(coord.right)):
            return beyond_affine(coord.left) + beyond_affine(coord.right)
        return work(coord)

    def access(index) -> int:
        return 1 + int(any(varies(coord) for coord in index)) + sum(beyond_affine(coord) for coord in index)

    size = 0
    for stmt in loop.body.iter():
        if isinstance(stmt, (Load, Write)):
            size += access(stmt.index)
        elif isinstance(stmt, Select):
            size += len(stmt.branches) - 1 + sum(work(branch.select) for branch in stmt.branches)
        elif isinstance(stmt, (Accum, Cond, Loop, StridedLoop)):
            size += 1 + sum(work(expression) for expression in stmt.expressions())
        else:
            size += sum(work(expression) for expression in stmt.expressions())
    return size


def _cost(term: Expression, forms: dict[str, str]) -> int:
    """The instructions ``term``'s own operation takes: a math function's from ``_COST``, one for any other."""
    if isinstance(term, FunctionCallExpression):
        return _COST.get(forms.get(term.name, term.name), 1)
    return 1 if isinstance(term, (BinaryExpression, CastExpression, TernaryExpression)) else 0
